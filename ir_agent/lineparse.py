"""结构化行的解析 —— 四个定性模块共用一份。

**为什么单独成模块。** 四个模块（宏观定性、战略、产业链、情景）都让模型
按 `关键词: 字段 | 字段 | …` 的格式输出，各自写了一遍
`^\\s*关键词\\s*[:：]\\s*(.+)$`。跑长电时宏观定性连挂三次，取回原始输出
才发现模型写的是:

    传导路径：

    1. 传导: 7月政治局会议加大逆周期调节 | 稳增长发力 → … | 利好 | 「原文」
    2. 传导: 日本收紧光刻胶出口管制 | … | 利好 | 「原文」

内容完全合格 —— 三条完整传导链、逐字引文俱全。但「1. 」这个列表前缀让
行首不再是关键词，正则一条都匹配不上，解析出 0 条，于是报「传导路径至少
2 条」。**模型每次都这么排版（要求「至少两条」时用编号列表是最自然的
写法），于是每次都失败** —— 确定性的不可满足，重试多少次都一样。

这类格式噪声还包括 `- `、`* `、`• `、`一、`、以及把关键词加粗成 `**传导**:`。
一处修不如一处定义 —— 与 aggregates.ebit()、parent_first() 同一条道理。
"""

from __future__ import annotations

import re

# 行首允许出现的列表前缀与强调标记。**只吃噪声，不吃内容。**
_PREFIX = (r"(?:[-*•·]\s*)?"                       # - / * / • / ·
           r"(?:\d{1,2}\s*[.、)）]\s*)?"            # 1. / 2、/ 3)
           r"(?:[一二三四五六七八九十]+\s*[、.]\s*)?"  # 一、二、
           r"[*＊]{0,2}\s*"                         # **加粗**
           r"`?")                                    # `整行包在反引号里`


# 行的内容：普通字符，或成对的 `代码片段`。**行尾落单的那个反引号不算内容** ——
# 那是整行包裹的收尾（生益科技第二次调用 2026-10-14：提示词把格式行写成单行
# 反引号，提出者照抄，三轮全写成 `公式: 营收 = …`，一行都没认出来）。内容里
# 成对的反引号（`陷阱: 注意 `上期(营收)``）照旧是内容。落单的反引号出现在行中
# 间时走后备分支 `.+?`，与改之前一样整行认。
_BODY = r"(?:[^`\n]|`[^`\n]*`)+?"


def keyed(name: str) -> re.Pattern[str]:
    """匹配 `关键词: 其余内容` 的一行，容忍列表前缀、加粗标记与整行反引号。"""
    return re.compile(rf"^\s*{_PREFIX}{name}[*＊]{{0,2}}\s*[:：]\s*"
                      rf"({_BODY}|.+?)`?[ \t]*$", re.MULTILINE)


def pick(field: str, allowed) -> str | None:
    """从一个字段里取出它属于哪个合法取值；取不到返回 None。

    **对格式宽容，对实质严格。** 实测模型写的是「低（证据强度弱）」——
    强度确实是「低」，后面那个括号是它主动补的说明。严格相等把整条判为
    非法，于是战略分析连挂三次、整节没能产出，而它给的判断本身没有问题。

    只认**开头**的合法取值，因此「低（…）」通过、「不低」不通过 ——
    宽容的是修饰与噪声，不是取值本身。
    """
    txt = field.strip().lstrip("*＊ ").strip()
    for a in sorted(allowed, key=len, reverse=True):
        if txt.startswith(a):
            return a
    return None
