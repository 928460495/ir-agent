"""结构化行的解析 —— 四个定性模块共用一份。

**为什么单独成模块。** 四个模块（宏观定性、战略、产业链、情景）都让模型
按 `关键词: 字段 | 字段 | …` 的格式输出，各自写了一遍
`^\\s*关键词\\s*[:：]\\s*(.+)$`。跑长电时宏观定性连挂三次，取回原始输出
才发现模型写的是:

    传导路径：

    1. 传导: 7月政治局会议加大逆周期调节 | 稳增长发力 → … | 利好 | 「原文」
    2. 传导: 日本收紧光刻胶出口管制 | … | 利好 | 「原文」

内容完全合格 —— 三条完整传导链、逐字引文俱全。但「1. 」这个列表前缀让
行首不再是关键词，正则一条都匹配不上，解析出 0 条，于是报「传导路径至少
2 条」。**模型每次都这么排版（要求「至少两条」时用编号列表是最自然的
写法），于是每次都失败** —— 确定性的不可满足，重试多少次都一样。

这类格式噪声还包括 `- `、`* `、`• `、`一、`、以及把关键词加粗成 `**传导**:`。
一处修不如一处定义 —— 与 aggregates.ebit()、parent_first() 同一条道理。
"""

from __future__ import annotations

import re

# 行首允许出现的列表前缀与强调标记。**只吃噪声，不吃内容。**
_PREFIX = (r"(?:[-*•·]\s*)?"                       # - / * / • / ·
           r"(?:\d{1,2}\s*[.、)）]\s*)?"            # 1. / 2、/ 3)
           r"(?:[一二三四五六七八九十]+\s*[、.]\s*)?"  # 一、二、
           r"[*＊]{0,2}\s*")                        # **加粗**


def keyed(name: str) -> re.Pattern[str]:
    """匹配 `关键词: 其余内容` 的一行，容忍列表前缀与加粗标记。"""
    return re.compile(rf"^\s*{_PREFIX}{name}[*＊]{{0,2}}\s*[:：]\s*(.+)$",
                      re.MULTILINE)
